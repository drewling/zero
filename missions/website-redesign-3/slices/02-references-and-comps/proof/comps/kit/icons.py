def rects(bitmap: str):
    rows = bitmap.strip("\n").split("\n")
    w = max(len(r) for r in rows)
    ink, paper = [], []
    for y, row in enumerate(rows):
        x = 0
        while x < len(row):
            ch = row[x]
            if ch in "#.":
                start = x
                while x < len(row) and row[x] == ch:
                    x += 1
                (ink if ch == "#" else paper).append((start, y, x - start))
            else:
                x += 1
    return w, len(rows), ink, paper


def path(runs):
    return "".join(f"M{x} {y}h{n}v1h-{n}z" for x, y, n in runs)


out = ['<svg xmlns="http://www.w3.org/2000/svg" style="display:none">']
sizes = {}
for name, bmp in ICONS.items():
    w, h, ink, paper = rects(bmp)
    sizes[name] = (w, h)
    out.append(f'<symbol id="{name}" viewBox="0 0 {w} {h}" shape-rendering="crispEdges">'
               f'<path fill="#fff" d="{path(paper)}"/><path fill="#000" d="{path(ink)}"/></symbol>')
out.append("</svg>")
Path(__file__).with_name("icons.svg").write_text("\n".join(out) + "\n")
for k, (w, h) in sizes.items():
    print(f"{k}: {w}x{h}")
